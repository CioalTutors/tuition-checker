-- ==========================================================
-- SECURE ALLOWED TEACHERS TABLE & SEED DATA
-- This ensures the Google Sheet can remain 100% PRIVATE.
-- No user can read any other teacher's email from this table.
-- ==========================================================

CREATE TABLE IF NOT EXISTS public.allowed_teachers (
    email TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.allowed_teachers ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any
DROP POLICY IF EXISTS "Users can verify their own email" ON public.allowed_teachers;
DROP POLICY IF EXISTS "Admins can manage allowed teachers" ON public.allowed_teachers;

-- Policy 1: Authenticated users can ONLY check if THEIR OWN email is approved
-- Strict privacy: Users CANNOT select * or scrape any other teacher's email!
CREATE POLICY "Users can verify their own email"
ON public.allowed_teachers
FOR SELECT
TO authenticated
USING (LOWER(email) = LOWER(auth.jwt() ->> 'email'));

-- Policy 2: Admins have full access
CREATE POLICY "Admins can manage allowed teachers"
ON public.allowed_teachers
FOR ALL
TO authenticated
USING (
    (LOWER(auth.jwt() ->> 'email') = 'cambridgeigcseoaleveltutors@gmail.com')
)
WITH CHECK (
    (LOWER(auth.jwt() ->> 'email') = 'cambridgeigcseoaleveltutors@gmail.com')
);

DROP POLICY IF EXISTS "Allow automated form submissions to add emails" ON public.allowed_teachers;

-- Policy 3: Allow Google Apps Script (with anon key) to insert new emails from Google Forms
CREATE POLICY "Allow automated form submissions to add emails"
ON public.allowed_teachers
FOR INSERT
TO anon, authenticated
WITH CHECK (email IS NOT NULL AND email LIKE '%@%.%');

